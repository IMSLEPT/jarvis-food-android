"""Package reviewed editorial images without altering the recipe/nutrition database.

Inputs are images produced with the built-in image tool and visually reviewed.
This script only converts their format/size and records the exact recipe/step.
Usage: python tools/photography/prepare.py /path/to/reviewed-inputs.json
"""
from pathlib import Path
import hashlib
import json
import re
import sys
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'app/src/main/assets'
SOURCE = Path(__file__).resolve().parent
INDEX = ROOT / 'app/src/main/java/com/jarvis/food/ui/EditorialPhotos.kt'


def subject(recipes, key):
    if key in recipes:
        return recipes[key], None
    match = re.fullmatch(r'(.+)_s(\d+)', key)
    if not match or match[1] not in recipes:
        raise ValueError(f'Unknown photo key: {key}')
    recipe, step = recipes[match[1]], int(match[2])
    if not 0 <= step < len(recipe['steps']):
        raise ValueError(f'Unknown step: {key}')
    return recipe, step


def write_index(records):
    pairs = '\n'.join(f'        "{key}" to "{value["asset"]}",' for key, value in sorted(records.items()))
    INDEX.write_text('''package com.jarvis.food.ui

/** Generated by tools/photography/prepare.py. Only reviewed, packaged images.
 * Original recipe IDs, quantities, calculations and user photos stay intact. */
object EditorialPhotos {
    private val assets = mapOf(
''' + pairs + '''
    )

    fun asset(key: String, original: String?): String? = assets[key] ?: original
    fun contains(key: String): Boolean = key in assets
    val keys: Set<String> get() = assets.keys
    val paths: Set<String> get() = assets.values.toSet()
    fun step(recipeId: String, index: Int, original: String?): String? = asset("${recipeId}_s$index", original)
}
''')


def main():
    recipes = {r['id']: r for r in json.loads((ASSETS / 'recipes.json').read_text())['recipes']}
    manifest = SOURCE / 'approved.json'
    records = json.loads(manifest.read_text()) if manifest.exists() else {}
    inputs = json.loads(Path(sys.argv[1]).read_text())
    for item in inputs:
        key = item['id']
        recipe, step = subject(recipes, key)
        relative = f'photography/{key}.webp'
        dst = ASSETS / relative
        dst.parent.mkdir(exist_ok=True)
        if 'reuse' in item:
            if item['reuse'] not in records:
                raise ValueError(f'Missing reviewed image: {item["reuse"]}')
            relative = records[item['reuse']]['asset']
            dst = ASSETS / relative
        else:
            with Image.open(item['path']) as image:
                image = ImageOps.exif_transpose(image).convert('RGB')
                image.thumbnail((1280, 1280), Image.Resampling.LANCZOS)
                temporary = dst.with_suffix('.webp.tmp')
                image.save(temporary, format='WEBP', quality=85, method=6)
                if temporary.stat().st_size < 10_000:
                    raise ValueError(f'Empty or incomplete image: {key}')
                temporary.replace(dst)
        records[key] = {
            'asset': relative,
            'recipeId': recipe['id'],
            'stepIndex': step,
            'subject': recipe['name'] if step is None else recipe['steps'][step],
            'kind': 'ai_illustration',
            'generator': 'built-in image_gen',
            'prompt': item.get('prompt', records.get(item.get('reuse'), {}).get('prompt', '')),
            'sha256': hashlib.sha256(dst.read_bytes()).hexdigest(),
        }
    manifest.write_text(json.dumps(records, ensure_ascii=False, indent=2) + '\n')
    write_index(records)
    print(f'Packaged {len(records)} reviewed recipe/step images.')


if __name__ == '__main__':
    main()
